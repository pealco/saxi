import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { resolve } from "node:path";
import { build } from "esbuild";

const clang =
  process.env.WASM_CLANG ??
  (existsSync("/opt/homebrew/opt/llvm/bin/clang") ? "/opt/homebrew/opt/llvm/bin/clang" : "clang");
const rustLld = resolve(
  homedir(),
  ".rustup/toolchains/stable-aarch64-apple-darwin/lib/rustlib/aarch64-apple-darwin/bin/rust-lld",
);
const linker = process.env.WASM_LD ?? (existsSync(rustLld) ? rustLld : "wasm-ld");
mkdirSync("dist/routing-wasm", { recursive: true });
const embed = process.argv.includes("--embed");
for (const mode of embed ? ["simd"] : ["scalar", "simd"]) {
  const object = `dist/routing-wasm/${mode}.o`;
  execFileSync(
    clang,
    [
      "--target=wasm32",
      "-O3",
      "-ffp-contract=off",
      "-fno-fast-math",
      "-fno-builtin",
      ...(mode === "simd" ? ["-msimd128"] : ["-fno-vectorize", "-fno-slp-vectorize"]),
      "-c",
      "src/routing-kernel.c",
      "-o",
      object,
    ],
    { stdio: "inherit" },
  );
  execFileSync(
    linker,
    [
      ...(linker.endsWith("rust-lld") ? ["-flavor", "wasm"] : []),
      "--no-entry",
      "--export=__heap_base",
      "--export-memory",
      "--initial-memory=2097152",
      "--max-memory=536870912",
      "-z",
      "stack-size=1048576",
      object,
      "-o",
      `dist/routing-wasm/${mode}.wasm`,
    ],
    { stdio: "inherit" },
  );
}
console.error("Built Wasm kernels without fast/relaxed math");

if (embed) {
  const hash = createHash("sha256").update(readFileSync("src/routing-kernel.c")).digest("hex");
  const bytes = readFileSync("dist/routing-wasm/simd.wasm").toString("base64");
  writeFileSync("src/routing-wasm.ts", `// Generated by npm run build:routing. Do not edit.\nexport const kernelSourceHash = "${hash}";\nexport const kernelBase64 =\n  "${bytes}";\n`);
  process.exit(0);
}

// Bundle the actual planner without importing the research fixture generators or runtime compiler.
const settings = readFileSync("tools/benchmark-routing-settings.mjs", "utf8");
const profileFunctions = settings.slice(
  settings.indexOf("function quiet("),
  settings.indexOf("export function evaluateSettings("),
);
if (!profileFunctions.includes("function tooling(options)")) throw new Error("Cannot locate shared profile functions");
await build({
  entryPoints: ["tools/routing-worker.mjs"],
  outfile: "dist/routing-wasm/worker.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  plugins: [
    {
      name: "planner-only",
      setup(b) {
        b.onLoad({ filter: /\/benchmark-routing-settings\.mjs$/ }, () => ({
          contents: `import assert from 'node:assert/strict'; import {Device} from '../src/planning.ts';
        export {preparePaths,replanGreedy as replan} from '../src/massager.ts'; ${profileFunctions} export {quiet,tooling};`,
          resolveDir: resolve("tools"),
          loader: "js",
        }));
        b.onLoad({ filter: /\/benchmark-routing\.mjs$/ }, () => ({
          contents: "export {plan,AxidrawFast} from '../src/planning.ts';",
          resolveDir: resolve("tools"),
          loader: "js",
        }));
      },
    },
  ],
});
console.error("Built isolated worker using Saxi source and shared profile functions");
